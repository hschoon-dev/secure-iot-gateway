#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

if [[ "${CI:-false}" != "true" && "${ALLOW_EPHEMERAL_TEST_ROTATION:-false}" != "true" ]]; then
  echo "ERROR: Refusing to rotate a non-CI workspace." >&2
  echo "Set ALLOW_EPHEMERAL_TEST_ROTATION=true only inside a disposable copy." >&2
  exit 2
fi

# A clean checkout intentionally contains no private keys. Generate an
# ephemeral CA and all service identities for this CI workspace only.
KEY_BITS="${KEY_BITS:-2048}" \
CA_DAYS="${CA_DAYS:-30}" \
CERT_DAYS="${CERT_DAYS:-30}" \
SKIP_NODE_RED_ROTATION=true \
  bash "${ROOT_DIR}/rotate-secrets.sh"

# This marker is deliberately outside component mounts. Production preflight
# rejects the complete runtime tree if it was generated for CI or local tests.
printf 'test-only: generated by tests/ci/prepare_test_secrets.sh\n' \
  > "${ROOT_DIR}/.runtime-secrets/.siot-test-only"
chmod 600 "${ROOT_DIR}/.runtime-secrets/.siot-test-only"

required_runtime_files=(
  "central-mo-client/certificates/python_client/mo_client_key.pem"
  "central-mo-client/certificates/python_client/mo_client_cert.der"
  "central-mo-client/certificates/trusted/interface_server_cert.der"
  "interface-partition/certificates/python-server/interface_server_key.pem"
  "interface-partition/certificates/python-server/interface_server_cert.der"
  "interface-partition/certificates/trusted/certs/mo_client_cert.der"
  "cpc-partition/opcua_client/certificates/cpc_client_key.pem"
  "cpc-partition/opcua_client/certificates/cpc_client_cert.der"
  "cpc-partition/opcua_client/certificates/trusted/brownfield_server_cert.der"
  "brownfield-opcua-server/opcua_secured_server/certificates/brownfield_server_key.pem"
  "brownfield-opcua-server/opcua_secured_server/certificates/brownfield_server_cert.der"
  "brownfield-opcua-server/opcua_secured_server/certificates/trusted/cpc_client_cert.der"
)

for path in "${required_runtime_files[@]}"; do
  if [[ ! -s "${ROOT_DIR}/.runtime-secrets/${path}" ]]; then
    echo "ERROR: Required ephemeral runtime secret is missing: ${path}" >&2
    exit 1
  fi
done

echo "Verified ${#required_runtime_files[@]} ephemeral OPC-UA runtime secret files."
